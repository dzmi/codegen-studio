# -*- coding: utf-8 -*-
"""Готовые промпты для копирования во внешние LLM."""

CODEGEN_JSON_RULES = """**ГЛАВНЫЕ ПРАВИЛА (ЧТОБЫ НЕ БЫЛО ОШИБОК):**
1. **Для Python-файлов НИКОГДА не используй `replace_block` для функций или классов!** Используй `replace_symbol`. Приложению не нужно копировать старое тело функции, оно само найдёт его через AST.
2. **`replace_block` используй ТОЛЬКО для замены глобальных переменных, словарей или 1-2 строк кода.** Поле `old` должно быть коротким и уникальным.
3. **Для вставки нового кода используй `insert_before` или `insert_after` с КОРОТКИМ уникальным якорем** (например, `def existing_function():`). НЕ бери в качестве якоря длинный кусок кода.
4. **`create_directory` не требует, чтобы папка уже существовала.** Просто передай путь.
5. **Экранирование:** двойные кавычки -> `\\\"`, обратные слеши -> `\\\\`, переводы строк -> `\\n`.

**ДОПУСТИМЫЕ ТИПЫ ДЕЙСТВИЙ:**
- `replace_symbol` (приоритет): {"type": "replace_symbol", "file": "path.py", "symbol": "Class.method", "new_code": "<полное определение>"}
- `replace_block`: {"type": "replace_block", "file": "path.py", "old": "<короткий уникальный фрагмент>", "new": "<новый код>"}
- `insert_before` / `insert_after`: {"type": "insert_before", "file": "path.py", "anchor": "def existing_func():", "content": "<новый код>"}
- `delete_block`: {"type": "delete_block", "file": "path.py", "old": "<короткий уникальный фрагмент>"}
- `create_file`, `create_directory`, `delete_file`

Верни ТОЛЬКО валидный JSON, без пояснений."""


CODEGEN_PROMPT = """Ты — эксперт по Python и автоматическому рефакторингу.
Сгенерируй JSON-инструкции для изменения кода проекта.

ЗАДАЧА:
[вставь задачу]

КОНТЕКСТ:
[вставь структуру или файл]

**КРИТИЧЕСКИ ВАЖНЫЕ ПРАВИЛА:**
- Если меняешь функцию или класс — ВСЕГДА используй `replace_symbol`. Не нужно копировать старый код.
- Если меняешь переменную — используй `replace_block` с коротким `old`.
- Если добавляешь код — используй `insert_before` с коротким якорем (например, `def function_name():`).
- НЕ используй `replace_block` для длинных кусков кода — это часто ломается из-за пробелов.

Верни ТОЛЬКО валидный JSON в блоке ```json ... ```.

""" + CODEGEN_JSON_RULES


CODE_REVIEW_PROMPT = """Ты — эксперт по Python. Проанализируй код и найди:
1. Ошибки
2. Потенциальные проблемы
3. Нарушения PEP8
4. Предложения по улучшению

Если пользователь просит исправить — верни JSON:
{"fixed_code": "...", "changes": [{"original": "...", "fixed": "...", "reason": "..."}]}

Не выдумывай несуществующие ошибки. Отвечай на русском."""


ARCHITECTURE_PROMPT = """Ты — архитектор ПО. Опиши архитектуру проекта: модули, их связи, поток данных.
Используй предоставленный JSON-контекст. Кратко, без воды."""


GENERAL_PROMPT = """Ты — опытный разработчик и технический писатель. Познакомься с проектом
и ответь на вопросы пользователя по существу.

Что делать:
1. Определи назначение проекта по именам файлов, docstrings, структуре.
2. Опиши ключевые модули и их связи (1-2 предложения на модуль).
3. Опиши основной поток данных / сценарии использования.
4. Если пользователь задаёт конкретный вопрос — ответь на него, опираясь на код.

**Не выдумывай** файлы и функции, которых нет в контексте. Если чего-то не хватает —
честно скажи, что нужно прикрепить.
"""


PROMPTS = {
    "Codegen (основной)": CODEGEN_PROMPT,
    "Code review": CODE_REVIEW_PROMPT,
    "Архитектура": ARCHITECTURE_PROMPT,
    "General (описание проекта)": GENERAL_PROMPT,
}


def get_prompt(name):
    return PROMPTS.get(name, "")


def list_prompts():
    return list(PROMPTS.keys())
